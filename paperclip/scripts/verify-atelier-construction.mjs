import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-webgl','--use-angle=swiftshader']})
try {
 const page=await browser.newPage({viewport:{width:1600,height:1000}})
 const errors=[];page.on('pageerror',error=>errors.push(String(error)))
 await page.goto('http://127.0.0.1:5173/ATL/design-studio')
 const panel=page.getByTestId('construction-history')
 await panel.getByText('Bộ sofa tầng 2',{exact:false}).waitFor({timeout:90000})
 await panel.getByRole('button',{name:/Bộ sofa tầng 2/}).click()
 await page.waitForTimeout(1000)
 let state=await page.evaluate(()=>window.__ATELIER_CONSTRUCTION_STATE__)
 assert(!state.active,'selection started construction')
 await page.screenshot({path:'../scratch/construction-history-selected.png'})
 await page.getByTestId('replay-delivery').click()
 await page.waitForTimeout(1200)
 state=await page.evaluate(()=>window.__ATELIER_CONSTRUCTION_STATE__)
 assert.equal(state.floor,2);assert(state.workerY>=state.floorY&&state.workerY<state.floorY+.03)
 assert(!state.visible.includes(state.active),'object is visible before placement')
 await panel.getByRole('button',{name:'Tạm dừng',exact:true}).click()
 await page.screenshot({path:'../scratch/construction-history-upper-floor.png'})
 await panel.getByRole('button',{name:'Tiếp tục',exact:true}).click()
 await page.waitForFunction(()=>{
   const state=window.__ATELIER_CONSTRUCTION_STATE__
   return state?.progress>.74 && state.visible.includes('construction:sofa-upper')
 },{},{timeout:30000})
 await page.screenshot({path:'../scratch/construction-history-placed.png'})
 await panel.getByRole('button',{name:'Dừng',exact:true}).click()
 await panel.getByRole('button',{name:'Replay toàn bộ',exact:true}).click()
 await page.waitForTimeout(1200)
 state=await page.evaluate(()=>window.__ATELIER_CONSTRUCTION_STATE__)
 assert(state.active);assert(!state.visible.includes('construction:sofa-upper'))
 assert.equal(state.activeIds.length,3)
 assert.equal(new Set(state.activeIds).size,3)
 assert.deepEqual(state.workers.map(worker=>worker.color),['#0f766e','#2563eb','#ea580c'])
 await panel.getByRole('button',{name:'2×',exact:true}).click()
 assert.equal(await page.evaluate(()=>window.__ATELIER_CONSTRUCTION_STATE__.speed),2)
 await panel.getByRole('button',{name:'Tạm dừng',exact:true}).click()
 const paused=await page.evaluate(()=>window.__ATELIER_CONSTRUCTION_STATE__.workers.map(worker=>worker.progress))
 await panel.getByRole('button',{name:'5×',exact:true}).click()
 await page.waitForTimeout(500)
 assert.deepEqual(await page.evaluate(()=>window.__ATELIER_CONSTRUCTION_STATE__.workers.map(worker=>worker.progress)),paused)
 await page.screenshot({path:'../scratch/construction-three-workers.png'})
 await panel.getByRole('button',{name:'Tiếp tục',exact:true}).click()
 await panel.getByRole('button',{name:'Dừng',exact:true}).click()
 await page.reload()
 await panel.getByRole('button',{name:/Bộ sofa tầng 2/}).waitFor({timeout:90000})
 state=await page.evaluate(()=>window.__ATELIER_CONSTRUCTION_STATE__)
 assert.equal(state.history.length,31);assert(!state.active)
 assert.equal(state.speed,1)
 for(const [name,id] of [['Lan can tầng 2','construction:railing-upper'],['Rèm tầng 2','construction:curtain-upper']]){
   await panel.getByRole('button',{name:new RegExp(name)}).click()
   await page.getByTestId('replay-delivery').click()
   await page.waitForTimeout(700)
   const detail=await page.evaluate(()=>window.__ATELIER_CONSTRUCTION_STATE__)
   assert.equal(detail.active,id);assert.equal(detail.floor,2);assert(!detail.visible.includes(id))
   await panel.getByRole('button',{name:'Dừng',exact:true}).click()
 }
 console.log(JSON.stringify({historyCount:state.history.length,errors,checks:'selection, upper floor, hidden before placement, pause/stop, replay all, persistence'},null,2))
 assert.equal(errors.length,0)
} finally {await browser.close()}
